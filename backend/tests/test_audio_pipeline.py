class TestNormalization:
    """normalize_waveform() must produce peak-normalised output."""

    def test_loud_signal_peak_is_1(self):
        from backend.audio.preprocessing import normalize_waveform
        waveform = np.array([0.1, 0.5, -0.3, 0.8, -0.2], dtype=np.float32)
        normed = normalize_waveform(waveform)
        assert abs(float(np.abs(normed).max()) - 1.0) < 1e-6

    def test_already_normalised_unchanged_in_peak(self):
        from backend.audio.preprocessing import normalize_waveform
        waveform = np.array([-1.0, 0.5, -0.3, 0.9], dtype=np.float32)
        normed = normalize_waveform(waveform)
        assert abs(float(np.abs(normed).max()) - 1.0) < 1e-6

    def test_quiet_signal_peak_after_normalize(self):
        """A quiet (but non-silent) waveform must be amplified to peak=1."""
        from backend.audio.preprocessing import normalize_waveform
        waveform = np.full(100, 0.001, dtype=np.float32)
        waveform[50] = 0.002
        normed = normalize_waveform(waveform)
        assert abs(float(np.abs(normed).max()) - 1.0) < 1e-5

    def test_silent_waveform_returned_unchanged(self):
        """All-zeros waveform must NOT be amplified (avoid Inf/NaN)."""
        from backend.audio.preprocessing import normalize_waveform
        silent = np.zeros(1000, dtype=np.float32)
        result = normalize_waveform(silent)
        assert np.all(result == 0.0), "Silent waveform should remain all-zeros"

    def test_output_dtype_is_float32(self):
        from backend.audio.preprocessing import normalize_waveform
        waveform = np.array([0.1, -0.5, 0.3], dtype=np.float32)
        result = normalize_waveform(waveform)
        assert result.dtype == np.float32

    def test_output_has_no_nan_or_inf(self):
        from backend.audio.preprocessing import normalize_waveform
        waveform = np.random.randn(4000).astype(np.float32)
        result = normalize_waveform(waveform)
        assert np.isfinite(result).all(), "Output must not contain NaN or Inf"

    def test_preprocess_audio_produces_normalised_peak(self):
        """Full pipeline with normalize=True must produce peak ≤ 1.0."""
        from backend.audio.preprocessing import preprocess_audio
        result = preprocess_audio(
            sample("sine_440hz_16k_quiet.wav"), normalize=True
        )
        peak = float(np.abs(result).max())
        assert peak <= 1.0 + 1e-6, f"Peak {peak:.6f} exceeds 1.0"
        # Quiet input must be amplified close to 1.0
        assert peak > 0.98, f"Expected peak close to 1.0, got {peak:.4f}"

    def test_preprocess_audio_no_normalize_preserves_amplitude(self):
        """With normalize=False, amplitude should stay sub-normalised."""
        from backend.audio.preprocessing import preprocess_audio
        result = preprocess_audio(
            sample("sine_440hz_16k_quiet.wav"), normalize=False
        )
        peak = float(np.abs(result).max())
        # Amplitude 0.01 sine, PCM round-trip — peak should be well below 1
        assert peak < 0.05, f"Expected low peak without normalization, got {peak:.4f}"


