class TestInMemorySynthetic:
    """Round-trip: generate WAV bytes → write temp file → preprocess → verify."""

    def _run(self, sr: int, channels: int = 1, freq: float = 440.0) -> np.ndarray:
        from backend.audio.preprocessing import preprocess_audio
        wav_bytes = _make_wav_bytes(
            sr=sr, freq=freq, duration=1.0, channels=channels
        )
        with tempfile.NamedTemporaryFile(suffix=".wav", delete=False) as f:
            f.write(wav_bytes)
            tmp_path = f.name
        try:
            return preprocess_audio(tmp_path)
        finally:
            os.unlink(tmp_path)

    def test_8khz_mono_to_16k(self):
        result = self._run(sr=8000, channels=1)
        assert result.dtype == np.float32
        assert result.ndim == 1
        # 1 s upsampled: expect ~16000 samples
        assert abs(result.size - 16000) < 800

    def test_44khz_stereo_to_16k_mono(self):
        result = self._run(sr=44100, channels=2)
        assert result.ndim == 1, "Must be mono"
        assert result.dtype == np.float32
        # 1 s downsampled: expect ~16000 samples
        assert abs(result.size - 16000) < 800

    def test_already_16khz_mono_passthrough(self):
        result = self._run(sr=16000, channels=1)
        assert result.ndim == 1
        assert result.dtype == np.float32
        # 1 s @ 16 kHz = 16000 samples exactly
        assert abs(result.size - 16000) < 200

    def test_no_nan_in_any_output(self):
        for sr, ch in [(8000, 1), (16000, 1), (22050, 2), (44100, 1)]:
            result = self._run(sr=sr, channels=ch)
            assert np.isfinite(result).all(), f"NaN/Inf found for sr={sr} ch={ch}"


