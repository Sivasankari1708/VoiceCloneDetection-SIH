def _make_wav_bytes(
    sr: int = 16000,
    freq: float = 440.0,
    duration: float = 0.5,
    amplitude: float = 0.5,
    channels: int = 1,
    sampwidth: int = 2,
) -> bytes:
    """Create in-memory WAV bytes for a pure sine wave."""
    n = int(sr * duration)
    t = np.linspace(0, duration, n, endpoint=False)
    data = (amplitude * np.sin(2 * math.pi * freq * t)).astype(np.float32)
    if channels == 2:
        data = np.stack([data, data * 0.8], axis=1).flatten()
    pcm = (data * (2 ** (sampwidth * 8 - 1) - 1)).astype(
        np.int16 if sampwidth == 2 else np.int32
    )
    import io
    buf = io.BytesIO()
    with wave.open(buf, "wb") as wf:
        wf.setnchannels(channels)
        wf.setsampwidth(sampwidth)
        wf.setframerate(sr)
        wf.writeframes(pcm.tobytes())
    return buf.getvalue()


